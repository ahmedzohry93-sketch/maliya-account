const dicts: Record<Lang, Dict> = { ar, en };

type Ctx = {
  lang: Lang;
  t: (k: string) => string;
  setLang: (l: Lang) => void;
  dir: "rtl" | "ltr";
  fmt: (n: number, opts?: Intl.NumberFormatOptions) => string;
};
const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    const saved = (typeof window !== "undefined" && (localStorage.getItem("lang") as Lang)) || "ar";
    setLangState(saved);
  }, []);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = (l: Lang) => {
    if (typeof window !== "undefined") localStorage.setItem("lang", l);
    setLangState(l);
  };

  const t = (k: string) => dicts[lang][k] ?? k;
  // Always use English (Latin) digits — force en-US locale regardless of lang
  const fmt = (n: number, opts?: Intl.NumberFormatOptions) =>
    new Intl.NumberFormat("en-US", { maximumFractionDigits: 2, ...opts }).format(n ?? 0);
  return <I18nCtx.Provider value={{ lang, setLang, t, dir: lang === "ar" ? "rtl" : "ltr", fmt }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("useI18n must be inside I18nProvider");
  return c;
}
